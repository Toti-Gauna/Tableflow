// P2-L3: pasaporte y fidelización con recarga, repetición, cancelación y reversión.

const pass = async (page: import('@playwright/test').Page, biz: string) =>
  (await state(page)).passports.find((p: { businessId: string; customerId: string | null }) => p.businessId === biz && p.customerId === null)

